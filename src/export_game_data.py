"""
Export the song catalog for the 3D game.

    python -m src.export_game_data

Writes assets/data/game_data.js (a plain <script> file the game page loads).
"""

import csv
import json
import os
from typing import Dict, List

from src.recommender import load_songs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Real songs (so iTunes can find preview clips). The fictional data/songs.csv
# belongs to the original recommender project and is left untouched.
CSV_PATH = os.path.join(ROOT, "data", "game_songs.csv")
OUT_PATH = os.path.join(ROOT, "assets", "data", "game_data.js")


def build_payload(songs: List[Dict]) -> Dict:
    """One room per genre, in a stable order."""
    return {
        "genres": sorted({s["genre"] for s in songs}),
        "moods": sorted({s["mood"] for s in songs}),
        "songs": songs,
    }


def load_game_songs(csv_path: str = CSV_PATH) -> List[Dict]:
    """
    Load the catalog, plus the optional itunes_track_id column.

    Some songs can't be found by iTunes text search, so a row may carry the exact
    iTunes track id (blank for the rest). load_songs() ignores that extra column,
    so it is attached here and the original recommender code stays untouched.
    """
    songs = load_songs(csv_path)
    with open(csv_path, encoding="utf-8", newline="") as f:
        ids = {int(row["id"]): (row.get("itunes_track_id") or "").strip() for row in csv.DictReader(f)}
    for song in songs:
        track_id = ids.get(song["id"], "")
        song["itunes_track_id"] = int(track_id) if track_id else None
    return songs


def main() -> None:
    payload = build_payload(load_game_songs())
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("// Generated by src/export_game_data.py. Do not edit by hand.\n")
        f.write("window.GAME_DATA = " + json.dumps(payload, indent=1) + ";\n")
    print(f"Wrote {OUT_PATH} ({len(payload['genres'])} genres, {len(payload['songs'])} songs)")


if __name__ == "__main__":
    main()
